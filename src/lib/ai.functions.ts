type Turn = { role: "user" | "assistant"; content: string };

export type ChatPayload = {
  name: string;
  gender: string;
  appearance: string;
  setting: string;
  personaName: string;
  personaAppearance: string;
  personaNotes: string;
  locked: string[];
  history: Turn[];
  userText: string;
};

function clip(value: unknown, n: number) {
  if (typeof value !== "string") return "";
  return value.trim().slice(0, n);
}

function friendly(msg: string) {
  return msg.slice(0, 240);
}

